# ====== Base class ======


class Message:
    """Fixed size message: the ID byte, then the fields in FORMAT."""

    ID: ClassVar[int]
    FORMAT: ClassVar[str]

    if TYPE_CHECKING:
        # the real constructor is the one generated by @dataclass
        def __init__(self, *args: object) -> None: ...

    @classmethod
    def size(cls) -> int:
        return struct.calcsize("<B" + cls.FORMAT)

    def pack(self) -> bytes:
        values = [getattr(self, f.name) for f in fields(cast("DataclassInstance", self))]
        return struct.pack("<B" + self.FORMAT, self.ID, *values)

    @classmethod
    def unpack(cls, data: bytes) -> Self:
        if len(data) != cls.size():
            raise MessageError(f"{cls.__name__}: expected {cls.size()} bytes, got {len(data)}")
        if data[0] != cls.ID:
            raise MessageError(f"{cls.__name__}: expected id {cls.ID}, got {data[0]}")
        hints = get_type_hints(cls)
        names = [f.name for f in fields(cast("type[DataclassInstance]", cls))]
        values = struct.unpack("<" + cls.FORMAT, data[1:])
        try:
            converted = [
                _convert(hints[name], value) for name, value in zip(names, values, strict=True)
            ]
        except ValueError as error:
            raise MessageError(f"{cls.__name__}: {error}") from error
        return cls(*converted)


def _convert(kind: object, value: object) -> object:
    """Turns a raw integer into its enum, if the field is typed with one."""
    if isinstance(kind, type) and issubclass(kind, IntEnum | IntFlag):
        return kind(value)
    return value


