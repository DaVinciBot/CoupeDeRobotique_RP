    move_id: int
    kind: MoveKind
    flags: MoveFlags
    x: float  # m
    y: float  # m
    theta: float  # rad
    distance: float  # m, negative = backwards
    max_speed: float  # m/s, 0 = configured limit
    max_accel: float  # m/s², 0 = configured limit


