def decode_message(data: bytes) -> Message | Print:
    """Message from the bytes given by decode_frame()."""
    if not data:
        raise MessageError("empty message")
    if data[0] == Print.ID:
        return Print(data[1:].decode("ascii", errors="replace"))
    cls = MESSAGES.get(data[0])
    if cls is None:
        raise MessageError(f"unknown message id {data[0]}")
    return cls.unpack(data)
