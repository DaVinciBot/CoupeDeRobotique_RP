@dataclass(frozen=True, slots=True)
class Print:
    """Debug text: the ID is followed by ASCII text, without fixed size."""

    ID: ClassVar[int] = 254
    text: str

    def pack(self) -> bytes:
        return bytes([self.ID]) + self.text.encode("ascii")


